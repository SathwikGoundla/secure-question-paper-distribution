import { useCallback, useEffect, useState, type FormEvent } from "react";
import { Link } from "react-router-dom";
import { getRecoveryCodeStatus, regenerateRecoveryCodes } from "../../api/endpoints";
import { ApiError } from "../../types/api";
import type { RecoveryCodeStatusResponse } from "../../types/auth";
import { Button } from "../../components/common/Button";
import { Input } from "../../components/common/Input";
import { ErrorBanner } from "../../components/common/ErrorBanner";
import { PageContainer } from "../../components/layout/PageContainer";

/**
 * Phase 7B — account security settings: one-time recovery codes.
 *
 * Recovery codes are a backup SECOND factor (used after your password if your authenticator app is
 * unavailable). They are generated by the backend, displayed here exactly once, and kept only in this
 * component's state: never in storage, never logged, never fetchable again (the status call returns
 * counts only). Generating a new set requires your current password and invalidates the old set.
 */
export function SecuritySettingsPage() {
  const [status, setStatus] = useState<RecoveryCodeStatusResponse | null>(null);
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState<string | null>(null);

  const [confirming, setConfirming] = useState(false);
  const [password, setPassword] = useState("");
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [formError, setFormError] = useState<string | null>(null);
  const [codes, setCodes] = useState<string[] | null>(null);
  const [copied, setCopied] = useState(false);

  const load = useCallback(() => {
    setLoading(true);
    setLoadError(null);
    getRecoveryCodeStatus()
      .then(setStatus)
      .catch((err: unknown) =>
        setLoadError(err instanceof ApiError ? err.userMessage : "Unable to load your security settings."),
      )
      .finally(() => setLoading(false));
  }, []);

  useEffect(() => {
    load();
  }, [load]);

  async function handleGenerate(event: FormEvent) {
    event.preventDefault();
    setFormError(null);
    if (!password) {
      setFormError("Enter your current password to continue.");
      return;
    }
    setIsSubmitting(true);
    try {
      const result = await regenerateRecoveryCodes(password);
      setCodes(result.codes);
      setCopied(false);
      setPassword("");
      setConfirming(false);
      load(); // refresh the counts (never the codes)
    } catch (err) {
      setFormError(err instanceof ApiError ? err.userMessage : "Unable to generate recovery codes.");
    } finally {
      setIsSubmitting(false);
    }
  }

  async function handleCopy() {
    if (!codes) return;
    try {
      await navigator.clipboard.writeText(codes.join("\n"));
      setCopied(true);
    } catch {
      setCopied(false);
      setFormError("Copying is not available in this browser. Select the codes and copy them manually.");
    }
  }

  function discardCodes() {
    setCodes(null);
    setCopied(false);
  }

  return (
    <PageContainer>
      <div className="auth-card">
        <h1>Security settings</h1>
        <p className="auth-subtitle">
          <Link to="/">← Back</Link>
        </p>

        <h2 className="admin-section-heading">Recovery codes</h2>
        <p className="auth-subtitle">
          Recovery codes let you sign in (after your password) if you lose access to your authenticator app. Each
          code works once.
        </p>

        {loading && <p aria-busy="true">Loading…</p>}
        {!loading && loadError && <ErrorBanner message={loadError} />}

        {!loading && status && !status.authenticator_active && (
          <p role="note">
            Set up an authenticator first. Recovery codes are a backup for it and can only be created once it is
            active.
          </p>
        )}

        {!loading && status && status.authenticator_active && (
          <>
            <p data-testid="recovery-summary">
              Unused recovery codes: <strong>{status.unused_count}</strong>
              {status.generated_at && <> (generated {new Date(status.generated_at).toLocaleString()})</>}
            </p>
            {status.unused_count === 0 && <p role="note">You have no unused recovery codes.</p>}
            {status.unused_count > 0 && status.unused_count <= 2 && (
              <p role="note">You are running low. Generate a new set soon.</p>
            )}

            {!codes && !confirming && (
              <Button type="button" onClick={() => setConfirming(true)}>
                {status.unused_count > 0 ? "Generate new recovery codes" : "Generate recovery codes"}
              </Button>
            )}

            {!codes && confirming && (
              <form onSubmit={handleGenerate} noValidate aria-label="Confirm generating recovery codes">
                <p role="note">
                  {status.unused_count > 0
                    ? `This invalidates your ${status.unused_count} unused recovery code${status.unused_count === 1 ? "" : "s"}. `
                    : ""}
                  The new codes are shown <strong>once</strong>. Store them somewhere safe (a password manager or a
                  printed copy kept securely).
                </p>
                <Input
                  id="regen-password"
                  label="Current password"
                  type="password"
                  autoComplete="current-password"
                  value={password}
                  onChange={(e) => setPassword(e.target.value)}
                  disabled={isSubmitting}
                  required
                />
                <ErrorBanner message={formError} />
                <Button type="submit" isLoading={isSubmitting}>
                  Generate codes
                </Button>
                <Button
                  type="button"
                  variant="secondary"
                  onClick={() => {
                    setConfirming(false);
                    setPassword("");
                    setFormError(null);
                  }}
                >
                  Cancel
                </Button>
              </form>
            )}
          </>
        )}

        {codes && (
          <section aria-label="Your new recovery codes" role="status">
            <p role="alert">
              <strong>Save these codes now.</strong> They will not be shown again, and anyone with a code and your
              password can sign in as you.
            </p>
            <ol data-testid="recovery-codes" className="recovery-code-list">
              {codes.map((c) => (
                <li key={c}>
                  <code>{c}</code>
                </li>
              ))}
            </ol>
            <ErrorBanner message={formError} />
            <Button type="button" onClick={() => void handleCopy()}>
              {copied ? "Copied" : "Copy all codes"}
            </Button>
            <Button type="button" variant="secondary" onClick={discardCodes}>
              I have saved these codes
            </Button>
          </section>
        )}
      </div>
    </PageContainer>
  );
}
