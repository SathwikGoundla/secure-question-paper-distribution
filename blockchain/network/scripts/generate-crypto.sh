#!/bin/bash
# generate-crypto.sh — Phase 5A, step 1.
#
# Generates static MSP crypto material for OrdererOrg (1 orderer) and
# Org1 (1 peer) using cryptogen. Requires the Fabric binary release
# (peer/orderer/cryptogen/configtxgen/osnadmin) to be on PATH or have
# FABRIC_BIN_DIR set to the directory containing them.
#
# Download the binaries (Linux/macOS) from:
#   https://github.com/hyperledger/fabric/releases/download/v2.5.16/hyperledger-fabric-<platform>-amd64-2.5.16.tar.gz
# Fabric does not publish native Windows binaries for peer/orderer/
# cryptogen — on Windows, run this from WSL2 (see docs/WINDOWS_SETUP.md
# in this same network/ directory), or use the docker-compose.yaml path
# instead (see network/docker-compose.yaml), where Docker Desktop's
# Linux VM runs official Fabric Docker images for you.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
NETDIR="$(dirname "$SCRIPT_DIR")"
FABRIC_BIN_DIR="${FABRIC_BIN_DIR:-$NETDIR/../bin}"

if ! command -v cryptogen >/dev/null 2>&1 && [ ! -x "$FABRIC_BIN_DIR/cryptogen" ]; then
  echo "ERROR: cryptogen not found on PATH and not found at $FABRIC_BIN_DIR/cryptogen"
  echo "Set FABRIC_BIN_DIR to the directory containing the extracted Fabric binaries, e.g.:"
  echo "  export FABRIC_BIN_DIR=/path/to/fabric-bin/bin"
  exit 1
fi
CRYPTOGEN="$(command -v cryptogen || echo "$FABRIC_BIN_DIR/cryptogen")"

echo "Using cryptogen: $CRYPTOGEN"
"$CRYPTOGEN" version

rm -rf "$NETDIR/organizations"
"$CRYPTOGEN" generate --config="$NETDIR/crypto-config/crypto-config.yaml" --output="$NETDIR/organizations"

echo
echo "Crypto material generated under: $NETDIR/organizations"
echo "(This directory is git-ignored — see blockchain/.gitignore. It must be"
echo " regenerated by anyone who clones this repository; it is never committed.)"
